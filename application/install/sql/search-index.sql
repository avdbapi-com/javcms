CREATE TABLE IF NOT EXISTS `javcms_vod_ft` (
  `FTS_DOC_ID` BIGINT UNSIGNED NOT NULL,
  `vod_id` INT UNSIGNED NOT NULL,
  `vod_time` INT UNSIGNED NOT NULL DEFAULT 0,
  `type_id` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `type_id_1` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `ft_text` MEDIUMTEXT CHARACTER SET latin1 COLLATE latin1_bin NOT NULL,
  PRIMARY KEY (`FTS_DOC_ID`),
  UNIQUE KEY `uk_vod` (`vod_id`),
  FULLTEXT KEY `ft` (`ft_text`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 ROW_FORMAT=COMPRESSED KEY_BLOCK_SIZE=8;
CREATE TABLE IF NOT EXISTS `javcms_vod_ft_term` (
  `term` VARCHAR(84) CHARACTER SET latin1 COLLATE latin1_bin NOT NULL PRIMARY KEY,
  `df` INT UNSIGNED NOT NULL, `df_sample` INT UNSIGNED NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS `javcms_vod_ft_queue` (
  `vod_id` INT UNSIGNED NOT NULL PRIMARY KEY, `queued_at` INT UNSIGNED NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS `javcms_vod_ft_replay` (
  `vod_id` INT UNSIGNED NOT NULL PRIMARY KEY, `queued_at` INT UNSIGNED NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS `javcms_vod_ft_state` (
  `id` TINYINT UNSIGNED NOT NULL PRIMARY KEY, `ready` TINYINT NOT NULL DEFAULT 0,
  `mode` VARCHAR(8) NOT NULL DEFAULT 'ft',
  `docs` INT UNSIGNED NOT NULL DEFAULT 0, `stale_ops` INT UNSIGNED NOT NULL DEFAULT 0,
  `out_of_order` INT UNSIGNED NOT NULL DEFAULT 0, `built_at` INT UNSIGNED NOT NULL DEFAULT 0,
  `langs` VARCHAR(255) NOT NULL DEFAULT 'en', `term_at` INT UNSIGNED NOT NULL DEFAULT 0,
  `docs_at_terms` INT UNSIGNED NOT NULL DEFAULT 0,
  `ms_per_read` DECIMAL(6,3) NOT NULL DEFAULT 0.100,
  `rebuild_started_at` INT UNSIGNED NOT NULL DEFAULT 0,
  `rebuild_due` VARCHAR(16) NOT NULL DEFAULT '',
  `bulk_job` INT UNSIGNED NOT NULL DEFAULT 0,
  `next_doc_id` BIGINT UNSIGNED NOT NULL DEFAULT 2,
  `inv_doc` BIGINT UNSIGNED NOT NULL DEFAULT 1,
  `inv_n` INT UNSIGNED NOT NULL DEFAULT 0,
  `term_doc` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `inv_ok` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `hw_time` INT UNSIGNED NOT NULL DEFAULT 0,
  `hw_id` INT UNSIGNED NOT NULL DEFAULT 0,
  `tok_doc` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `tok_n` INT UNSIGNED NOT NULL DEFAULT 0,
  `cut_doc` BIGINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS `javcms_vod_ft_map` (
  `term` VARCHAR(84) CHARACTER SET latin1 COLLATE latin1_bin NOT NULL PRIMARY KEY,
  `kind` TINYINT UNSIGNED NOT NULL,
  `df` INT UNSIGNED NOT NULL,
  `step` INT UNSIGNED NOT NULL,
  `last_doc` BIGINT UNSIGNED NOT NULL,
  `data` MEDIUMBLOB NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 ROW_FORMAT=COMPRESSED KEY_BLOCK_SIZE=8;
CREATE TABLE IF NOT EXISTS `javcms_vod_ft_mapt` (
  `term` VARCHAR(84) CHARACTER SET latin1 COLLATE latin1_bin NOT NULL,
  `chunk` SMALLINT UNSIGNED NOT NULL,
  `n` INT UNSIGNED NOT NULL,
  `last_doc` BIGINT UNSIGNED NOT NULL,
  `data` BLOB NOT NULL,
  PRIMARY KEY (`term`, `chunk`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `javcms_vod_ft_mapd` (
  `seq` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `doc` BIGINT UNSIGNED NOT NULL,
  `ft_text` MEDIUMTEXT CHARACTER SET latin1 COLLATE latin1_bin NOT NULL,
  PRIMARY KEY (`seq`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `javcms_vod_ft_inv` (
  `term` VARCHAR(84) CHARACTER SET latin1 COLLATE latin1_bin NOT NULL,
  `doc` BIGINT UNSIGNED NOT NULL,
  `vod_time` INT UNSIGNED NOT NULL DEFAULT 0,
  `vod_id` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`term`, `doc`),
  KEY `doc` (`doc`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `javcms_vod_ft_newtok` (
  `term` VARCHAR(84) CHARACTER SET latin1 COLLATE latin1_bin NOT NULL,
  `doc` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`term`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
